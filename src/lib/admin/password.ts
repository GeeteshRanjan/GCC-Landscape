import {
  randomBytes,
  scrypt as scryptCallback,
  timingSafeEqual,
} from "node:crypto";
import { promisify } from "node:util";

export { PASSWORD_MIN_LENGTH } from "./constants";

/**
 * Password hashing for the single admin account.
 *
 * There is no database, so there is no user table — one password, hashed, in the
 * environment. scrypt is used rather than a plain digest because the hash sits
 * in an env var that a platform dashboard will happily show to anyone with
 * project access; a fast hash there is a password in practice.
 *
 * Node's own crypto is enough, so no dependency is added. Parameters are stored
 * in the hash string, which means the cost can be raised later without
 * invalidating an existing value.
 *
 * No `server-only` marker, and that is deliberate rather than an omission. This
 * module is also imported by scripts/admin-hash.ts under `tsx`, where
 * `server-only` throws — and it needs no marker anyway: it reads no environment
 * and imports `node:crypto`, which a browser bundle cannot resolve. The markers
 * that matter are on session.ts, which touches cookies and the secret.
 */

const scrypt = promisify(scryptCallback) as (
  password: string | Buffer,
  salt: string | Buffer,
  keylen: number,
  options: { N: number; r: number; p: number; maxmem: number },
) => Promise<Buffer>;

/** ~100ms on a laptop, which is the point. */
const DEFAULT_PARAMS = { N: 16384, r: 8, p: 1 } as const;
const KEY_LENGTH = 64;
const SALT_LENGTH = 16;
/** scrypt's default maxmem (32 MB) is below what N=16384, r=8 needs. */
const MAXMEM = 64 * 1024 * 1024;

/**
 * `scrypt:N:r:p:saltBase64Url:keyBase64Url`
 *
 * Colons and base64url, not the conventional `$` and standard base64. The `$`
 * form is what every scrypt/argon2 library emits, and it is wrong here: this
 * value lives in an env file, and dotenv expands `$N` as a variable reference,
 * so `scrypt$16384$8$1$...` silently arrives as `scrypt` with the rest blank.
 * base64url then keeps `+`, `/` and `=` out of the value for the same reason —
 * env parsing should not have opinions about a hash.
 */
export async function hashPassword(
  password: string,
  params: { N: number; r: number; p: number } = DEFAULT_PARAMS,
): Promise<string> {
  const salt = randomBytes(SALT_LENGTH);
  const key = await scrypt(password, salt, KEY_LENGTH, { ...params, maxmem: MAXMEM });
  return [
    "scrypt",
    params.N,
    params.r,
    params.p,
    salt.toString("base64url"),
    key.toString("base64url"),
  ].join(":");
}

/**
 * Constant-time comparison against a stored hash. Returns false on a malformed
 * hash rather than throwing, so a misconfigured env var reads as "wrong
 * password" to the client while `describeHashProblem` gives the operator the
 * real reason in the server log.
 */
export async function verifyPassword(
  password: string,
  stored: string,
): Promise<boolean> {
  const parsed = parseHash(stored);
  if (!parsed) return false;

  let derived: Buffer;
  try {
    derived = await scrypt(password, parsed.salt, parsed.key.length, {
      N: parsed.N,
      r: parsed.r,
      p: parsed.p,
      maxmem: MAXMEM,
    });
  } catch {
    return false;
  }

  return (
    derived.length === parsed.key.length && timingSafeEqual(derived, parsed.key)
  );
}

interface ParsedHash {
  N: number;
  r: number;
  p: number;
  salt: Buffer;
  key: Buffer;
}

function parseHash(stored: string): ParsedHash | null {
  const parts = stored.trim().split(":");
  if (parts.length !== 6) return null;
  const [scheme, rawN, rawR, rawP, rawSalt, rawKey] = parts;
  if (scheme !== "scrypt") return null;

  const N = Number(rawN);
  const r = Number(rawR);
  const p = Number(rawP);
  if (![N, r, p].every((n) => Number.isInteger(n) && n > 0)) return null;

  try {
    const salt = Buffer.from(rawSalt ?? "", "base64url");
    const key = Buffer.from(rawKey ?? "", "base64url");
    if (salt.length === 0 || key.length === 0) return null;
    return { N, r, p, salt, key };
  } catch {
    return null;
  }
}

/**
 * Operator-facing diagnosis of `ADMIN_PASSWORD_HASH`. Never sent to the client —
 * a login response that distinguishes "misconfigured" from "wrong password"
 * tells an attacker which one they are looking at.
 */
export function describeHashProblem(stored: string | undefined): string | null {
  if (!stored) {
    return "ADMIN_PASSWORD_HASH is not set. Run `npm run admin:hash` and put the result in your environment.";
  }
  if (!parseHash(stored)) {
    return (
      "ADMIN_PASSWORD_HASH is not a valid scrypt hash (expected scrypt:N:r:p:salt:key). " +
      "Re-run `npm run admin:hash`. If the value contains `$`, it was generated by an " +
      "older build and dotenv will have eaten part of it."
    );
  }
  return null;
}
